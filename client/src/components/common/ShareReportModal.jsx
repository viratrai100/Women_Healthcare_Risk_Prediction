/**
 * ShareReportModal.jsx
 *
 * "Share with Doctor" modal — lets the patient:
 *   1. Download the PDF report (via generateHealthReport)
 *   2. Copy a pre-written email template to the clipboard
 *   3. Open a mailto: link that pre-fills the email body
 *
 * Props:
 *   isOpen      {boolean}   — controls visibility
 *   onClose     {function}  — called when the modal should close
 *   aiResult    {object}    — canonical AI result object
 *   user        {object}    — { name, email } from AuthContext
 *   inputData   {object}    — raw health assessment form data
 */

import { useState, useEffect, useRef } from 'react';
import { generateHealthReport }        from '@/utils/generateHealthReport.js';

// ─────────────────────────────────────────────────────────────────────────────
// Helpers
// ─────────────────────────────────────────────────────────────────────────────

function cap(s) { return s ? s.charAt(0).toUpperCase() + s.slice(1) : ''; }

function buildEmailBody(aiResult, user) {
  const { riskScore = 0, riskLevel = 'low', summary = '', diseaseRisks = [], recommendations = [] } = aiResult ?? {};
  const patientName = user?.name || 'Your Patient';

  const topDiseases = [...diseaseRisks]
    .sort((a, b) => b.riskScore - a.riskScore)
    .slice(0, 3)
    .map((d) => `  • ${d.disease}: ${d.riskScore}% (${cap(d.riskLevel || 'moderate')})`)
    .join('\n');

  const topRecs = recommendations
    .filter((r) => r.priority === 'urgent' || r.priority === 'high')
    .slice(0, 3)
    .map((r) => `  • [${cap(r.priority)}] ${r.action}`)
    .join('\n');

  return `Dear Doctor,

I am ${patientName} and I am sharing my AI-generated health risk analysis report for your review.

OVERALL HEALTH SCORE: ${riskScore} / 100
RISK LEVEL: ${cap(riskLevel)}

SUMMARY:
${summary || 'Please refer to the attached PDF report for the detailed AI analysis.'}

TOP DISEASE RISKS:
${topDiseases || '  • See attached report.'}

HIGH-PRIORITY RECOMMENDATIONS:
${topRecs || '  • See attached report.'}

Please find the full PDF report attached to this email for detailed disease-by-disease breakdown and personalised recommendations.

Could we please schedule an appointment at your earliest convenience to discuss these results?

Regards,
${patientName}
${user?.email ? `Email: ${user.email}` : ''}

--
This report was generated by AI Women's Healthcare · Gemini AI
This is an AI-generated assessment for informational purposes only and does not constitute medical advice.`.trim();
}

// ─────────────────────────────────────────────────────────────────────────────
// ShareReportModal
// ─────────────────────────────────────────────────────────────────────────────

export default function ShareReportModal({ isOpen, onClose, aiResult, user, inputData }) {
  const [downloading, setDownloading] = useState(false);
  const [copyState,   setCopyState]   = useState('idle'); // 'idle' | 'copied' | 'error'
  const [doctorEmail, setDoctorEmail] = useState('');
  const backdropRef = useRef(null);

  const emailBody    = buildEmailBody(aiResult, user);
  const emailSubject = `Health Report — ${user?.name || 'Patient'} — AI Risk Analysis`;

  // Close on Escape
  useEffect(() => {
    if (!isOpen) return;
    const handler = (e) => { if (e.key === 'Escape') onClose(); };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  }, [isOpen, onClose]);

  // Lock body scroll
  useEffect(() => {
    if (isOpen) {
      document.body.style.overflow = 'hidden';
    } else {
      document.body.style.overflow = '';
    }
    return () => { document.body.style.overflow = ''; };
  }, [isOpen]);

  if (!isOpen) return null;

  // ── Handlers ────────────────────────────────────────────────────────────────

  async function handleDownload() {
    if (downloading) return;
    setDownloading(true);
    try {
      await generateHealthReport({ aiResult, user, inputData });
    } catch (err) {
      console.error('PDF generation failed:', err);
    } finally {
      setDownloading(false);
    }
  }

  async function handleCopyEmail() {
    try {
      await navigator.clipboard.writeText(emailBody);
      setCopyState('copied');
      setTimeout(() => setCopyState('idle'), 2500);
    } catch {
      setCopyState('error');
      setTimeout(() => setCopyState('idle'), 2500);
    }
  }

  function handleMailto() {
    const to      = encodeURIComponent(doctorEmail);
    const subject = encodeURIComponent(emailSubject);
    const body    = encodeURIComponent(emailBody);
    const limit   = 1800; // some email clients truncate very long mailto bodies
    const truncatedBody = body.length > limit ? body.slice(0, limit) + encodeURIComponent('\n\n[Body truncated — see attached PDF]') : body;
    window.open(`mailto:${to}?subject=${subject}&body=${truncatedBody}`, '_blank');
  }

  // ── Render ──────────────────────────────────────────────────────────────────

  const copyLabel = {
    idle:   'Copy Email Template',
    copied: '✓ Copied!',
    error:  'Copy Failed',
  }[copyState];

  const copyClass = {
    idle:   'border-surface-border text-slate-300 hover:border-primary-500/60 hover:text-white hover:bg-surface-card',
    copied: 'border-emerald-500/50 text-emerald-400 bg-emerald-500/10',
    error:  'border-rose-500/50 text-rose-400 bg-rose-500/10',
  }[copyState];

  return (
    /* Backdrop */
    <div
      ref={backdropRef}
      className="fixed inset-0 z-[9999] flex items-center justify-center p-4"
      style={{ background: 'rgba(0,0,0,0.75)', backdropFilter: 'blur(6px)' }}
      onClick={(e) => { if (e.target === backdropRef.current) onClose(); }}
      role="dialog"
      aria-modal="true"
      aria-labelledby="share-modal-title"
    >
      {/* Panel */}
      <div
        className="relative w-full max-w-lg rounded-2xl border border-surface-border shadow-2xl"
        style={{
          background: 'linear-gradient(135deg, #141428 0%, #0f0f1a 100%)',
          boxShadow: '0 0 80px rgba(236,72,153,0.12), 0 25px 50px rgba(0,0,0,0.6)',
          animation: 'modalIn 0.25s cubic-bezier(0.34,1.56,0.64,1) both',
        }}
      >
        {/* Glow accent */}
        <div
          className="absolute -top-px left-1/2 -translate-x-1/2 h-px w-3/4 rounded-full"
          style={{ background: 'linear-gradient(90deg, transparent, #ec4899, transparent)' }}
          aria-hidden="true"
        />

        {/* Header */}
        <div className="flex items-center justify-between px-6 pt-6 pb-4 border-b border-surface-border">
          <div className="flex items-center gap-3">
            <div className="h-10 w-10 rounded-xl bg-primary-500/15 border border-primary-500/30 flex items-center justify-center text-xl flex-shrink-0">
              🩺
            </div>
            <div>
              <h2 id="share-modal-title" className="text-lg font-bold text-white">Share with Doctor</h2>
              <p className="text-xs text-slate-400 mt-0.5">Send your AI health report to your physician</p>
            </div>
          </div>
          <button
            id="share-modal-close-btn"
            onClick={onClose}
            aria-label="Close"
            className="h-8 w-8 rounded-lg flex items-center justify-center text-slate-500 hover:text-white hover:bg-slate-700/60 transition-colors"
          >
            <svg width="14" height="14" viewBox="0 0 14 14" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round">
              <path d="M1 1l12 12M13 1L1 13"/>
            </svg>
          </button>
        </div>

        {/* Body */}
        <div className="px-6 py-5 flex flex-col gap-5">

          {/* Step 1 — Download PDF */}
          <div className="rounded-xl border border-surface-border bg-surface-card/40 p-4">
            <div className="flex items-start gap-3">
              <div className="h-8 w-8 rounded-lg bg-primary-500/15 border border-primary-500/20 flex items-center justify-center text-sm font-bold text-primary-400 flex-shrink-0">
                1
              </div>
              <div className="flex-1 min-w-0">
                <p className="text-sm font-semibold text-white mb-0.5">Download your PDF Report</p>
                <p className="text-xs text-slate-400 leading-relaxed">
                  Generate a professional multi-page PDF with your health score, disease risks, and recommendations.
                  Attach it to the email you'll send your doctor.
                </p>
                <button
                  id="share-download-pdf-btn"
                  onClick={handleDownload}
                  disabled={downloading}
                  className="mt-3 inline-flex items-center gap-2 px-4 py-2 rounded-xl bg-gradient-to-r from-primary-600 to-primary-700 hover:from-primary-500 hover:to-primary-600 text-white text-xs font-semibold shadow-lg shadow-primary-500/25 transition-all duration-200 disabled:opacity-60 disabled:cursor-not-allowed"
                >
                  {downloading ? (
                    <>
                      <span className="h-3.5 w-3.5 border-2 border-white/30 border-t-white rounded-full animate-spin" />
                      Generating PDF…
                    </>
                  ) : (
                    <>
                      <svg width="13" height="13" viewBox="0 0 20 20" fill="currentColor">
                        <path fillRule="evenodd" d="M3 17a1 1 0 011-1h12a1 1 0 110 2H4a1 1 0 01-1-1zm3.293-7.707a1 1 0 011.414 0L9 10.586V3a1 1 0 112 0v7.586l1.293-1.293a1 1 0 111.414 1.414l-3 3a1 1 0 01-1.414 0l-3-3a1 1 0 010-1.414z" clipRule="evenodd"/>
                      </svg>
                      Download PDF Report
                    </>
                  )}
                </button>
              </div>
            </div>
          </div>

          {/* Step 2 — Email your doctor */}
          <div className="rounded-xl border border-surface-border bg-surface-card/40 p-4">
            <div className="flex items-start gap-3">
              <div className="h-8 w-8 rounded-lg bg-primary-500/15 border border-primary-500/20 flex items-center justify-center text-sm font-bold text-primary-400 flex-shrink-0">
                2
              </div>
              <div className="flex-1 min-w-0">
                <p className="text-sm font-semibold text-white mb-0.5">Email your Doctor</p>
                <p className="text-xs text-slate-400 mb-3 leading-relaxed">
                  Enter your doctor's email address below. We'll pre-fill a professional email with your report summary.
                </p>

                {/* Doctor email input */}
                <label htmlFor="doctor-email-input" className="block text-xs font-medium text-slate-400 mb-1.5">
                  Doctor's Email Address
                </label>
                <input
                  id="doctor-email-input"
                  type="email"
                  value={doctorEmail}
                  onChange={(e) => setDoctorEmail(e.target.value)}
                  placeholder="doctor@clinic.com"
                  className="w-full bg-surface-dark border border-surface-border rounded-xl px-3 py-2 text-sm text-white placeholder-slate-600 focus:outline-none focus:border-primary-500/60 focus:ring-1 focus:ring-primary-500/20 transition-colors"
                />

                {/* Email action buttons */}
                <div className="flex flex-wrap gap-2 mt-3">
                  <button
                    id="share-open-email-btn"
                    onClick={handleMailto}
                    className="inline-flex items-center gap-2 px-4 py-2 rounded-xl bg-gradient-to-r from-primary-600 to-primary-700 hover:from-primary-500 hover:to-primary-600 text-white text-xs font-semibold shadow-lg shadow-primary-500/25 transition-all duration-200"
                  >
                    <svg width="13" height="13" viewBox="0 0 20 20" fill="currentColor">
                      <path d="M2.003 5.884L10 9.882l7.997-3.998A2 2 0 0016 4H4a2 2 0 00-1.997 1.884z"/>
                      <path d="M18 8.118l-8 4-8-4V14a2 2 0 002 2h12a2 2 0 002-2V8.118z"/>
                    </svg>
                    Open in Email App
                  </button>

                  <button
                    id="share-copy-email-btn"
                    onClick={handleCopyEmail}
                    className={`inline-flex items-center gap-2 px-4 py-2 rounded-xl text-xs font-medium border transition-all duration-200 ${copyClass}`}
                  >
                    {copyState === 'copied' ? (
                      <svg width="13" height="13" viewBox="0 0 20 20" fill="currentColor">
                        <path fillRule="evenodd" d="M16.707 5.293a1 1 0 010 1.414l-8 8a1 1 0 01-1.414 0l-4-4a1 1 0 011.414-1.414L8 12.586l7.293-7.293a1 1 0 011.414 0z" clipRule="evenodd"/>
                      </svg>
                    ) : (
                      <svg width="13" height="13" viewBox="0 0 20 20" fill="currentColor">
                        <path d="M8 3a1 1 0 011-1h2a1 1 0 110 2H9a1 1 0 01-1-1z"/>
                        <path d="M6 3a2 2 0 00-2 2v11a2 2 0 002 2h8a2 2 0 002-2V5a2 2 0 00-2-2 3 3 0 01-3 3H9a3 3 0 01-3-3z"/>
                      </svg>
                    )}
                    {copyLabel}
                  </button>
                </div>
              </div>
            </div>
          </div>

          {/* Email preview (collapsible) */}
          <details className="group rounded-xl border border-slate-700/40 bg-slate-800/20 overflow-hidden">
            <summary className="flex items-center justify-between cursor-pointer px-4 py-3 text-xs font-medium text-slate-400 hover:text-slate-300 select-none list-none transition-colors">
              <span className="flex items-center gap-2">
                <svg width="12" height="12" viewBox="0 0 20 20" fill="currentColor" className="text-slate-500">
                  <path fillRule="evenodd" d="M18 10a8 8 0 11-16 0 8 8 0 0116 0zm-7-4a1 1 0 11-2 0 1 1 0 012 0zM9 9a1 1 0 000 2v3a1 1 0 001 1h1a1 1 0 100-2v-3a1 1 0 00-1-1H9z" clipRule="evenodd"/>
                </svg>
                Preview email template
              </span>
              <svg width="12" height="12" viewBox="0 0 20 20" fill="currentColor" className="transition-transform duration-200 group-open:rotate-180 text-slate-500">
                <path fillRule="evenodd" d="M5.293 7.293a1 1 0 011.414 0L10 10.586l3.293-3.293a1 1 0 111.414 1.414l-4 4a1 1 0 01-1.414 0l-4-4a1 1 0 010-1.414z" clipRule="evenodd"/>
              </svg>
            </summary>
            <div className="border-t border-slate-700/40 px-4 py-3">
              <pre className="text-[10.5px] text-slate-400 leading-relaxed whitespace-pre-wrap font-mono overflow-auto max-h-48 scrollbar-thin">
                {emailBody}
              </pre>
            </div>
          </details>

        </div>

        {/* Footer */}
        <div className="px-6 pb-5">
          <p className="text-[10px] text-slate-600 text-center leading-relaxed">
            🔒 Your health data is never uploaded or stored by this sharing feature. The PDF is generated locally in your browser.
          </p>
        </div>
      </div>

      {/* Modal entrance animation */}
      <style>{`
        @keyframes modalIn {
          from { opacity: 0; transform: scale(0.92) translateY(12px); }
          to   { opacity: 1; transform: scale(1) translateY(0);       }
        }
      `}</style>
    </div>
  );
}
